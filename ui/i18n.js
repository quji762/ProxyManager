let lang = "zh";

function t(key, vars) {
  const table = (I18N[lang] || I18N.zh);
  let s = table[key] || I18N.zh[key] || key;
  if (vars) {
    Object.keys(vars).forEach((k) => {
      s = s.split("{" + k + "}").join(String(vars[k]));
    });
  }
  return s;
}

function setLang(next) {
  lang = next === "en" ? "en" : "zh";
  document.documentElement.lang = lang === "en" ? "en" : "zh-CN";
  applyI18n();
}

function applyI18n() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    if (el.id === "bgName" || el.id === "speedCap") return;
    // 全部测试 keeps its "测试中…" label while a batch run is in flight.
    if (el.id === "btnTestAll" && el.classList.contains("testing")) return;
    if (el.classList.contains("test-chip") &&
        (el.classList.contains("testing") || el.classList.contains("ok") ||
         el.classList.contains("fail"))) return;
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-tip]").forEach((el) => {
    el.dataset.tip = t(el.dataset.i18nTip);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nAria));
  });
  document.title = t("appName");
  const bg = document.getElementById("bgName");
  if (bg && typeof cfg !== "undefined" && !cfg.bg_path) bg.textContent = t("bgNone");
  if (typeof renderEndpoints === "function") renderEndpoints();
  if (typeof renderPorts === "function") renderPorts();
  if (typeof renderProfiles === "function") renderProfiles();
  if (typeof updateHero === "function") updateHero();
  // These are generated from t() at render time, not data-i18n nodes, so a
  // language switch must repaint them explicitly (otherwise the PAC hint and
  // the speed caption stay in the previous language).
  if (typeof renderPacHint === "function") renderPacHint();
  if (typeof renderSpeedCap === "function") renderSpeedCap();
  // History rows carry localized channel names; the backup list's action
  // buttons are generated (not data-i18n), so both must repaint on a language
  // switch. Backups only re-fetch while settings is open to avoid a backend
  // round-trip on the boot-time setLang.
  if (typeof renderHistory === "function") renderHistory();
  const sov = document.getElementById("settingsOv");
  if (sov && sov.classList.contains("show") && typeof renderBackupList === "function") renderBackupList();
}

function displayStatus(v) {
  const s = String(v == null ? "" : v);
  if (!s || s === "—" || s === "未设置" || s === "Not set") return t("unset");
  if (s === "未检测到" || s === "Not detected") return t("undetected");
  return s;
}
